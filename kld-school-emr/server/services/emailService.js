import nodemailer from 'nodemailer';
import { pool } from '../config/db.js';
import { env } from '../config/env.js';
import { uuid } from '../utils/ids.js';

let transporter;

function getTransporter() {
  if (transporter) return transporter;
  transporter = env.EMAIL_MODE === 'smtp'
    ? nodemailer.createTransport({
        host: env.SMTP_HOST,
        port: env.SMTP_PORT,
        secure: env.SMTP_SECURE,
        auth: env.SMTP_USER ? { user: env.SMTP_USER, pass: env.SMTP_PASSWORD } : undefined
      })
    : nodemailer.createTransport({ jsonTransport: true });
  return transporter;
}

export async function enqueueEmail({ recipient, subject, template, payload = {}, relatedType = null, relatedId = null }) {
  const id = uuid();
  await pool.execute(
    `INSERT INTO email_queue
      (id, recipient, subject, template, payload_json, status, attempts, next_attempt_at, related_type, related_id)
     VALUES (?, ?, ?, ?, ?, 'PENDING', 0, NOW(), ?, ?)`,
    [id, recipient, subject, template, JSON.stringify(payload), relatedType, relatedId]
  );
  return id;
}

function templateHtml(template, payload) {
  const clinicName = payload.clinicName || 'KLD Clinic';
  const title = payload.title || payload.subject || 'Clinic Notification';
  const message = payload.message || '';
  const actionUrl = payload.actionUrl;
  const actionLabel = payload.actionLabel || 'Open KLD Clinic Portal';
  return `<!doctype html>
  <html><body style="margin:0;background:#f4f7f5;font-family:Arial,sans-serif;color:#1a202c">
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0"><tr><td align="center" style="padding:32px 16px">
      <table role="presentation" width="600" cellpadding="0" cellspacing="0" style="max-width:600px;background:#fff;border-radius:18px;overflow:hidden;border:1px solid #e2e8f0">
        <tr><td style="background:#0A5C36;color:#fff;padding:24px 28px"><div style="font-size:12px;letter-spacing:.14em;text-transform:uppercase;color:#FCD116">KLD School Clinic</div><h1 style="font-size:24px;margin:8px 0 0">${escapeHtml(clinicName)}</h1></td></tr>
        <tr><td style="padding:30px"><h2 style="font-size:20px;margin:0 0 14px">${escapeHtml(title)}</h2><div style="font-size:15px;line-height:1.7">${message}</div>
          ${actionUrl ? `<p style="margin:26px 0 0"><a href="${escapeHtml(actionUrl)}" style="display:inline-block;background:#0A5C36;color:#fff;text-decoration:none;padding:12px 18px;border-radius:10px;font-weight:700">${escapeHtml(actionLabel)}</a></p>` : ''}
        </td></tr>
        <tr><td style="padding:18px 28px;background:#f7fafc;color:#64748b;font-size:12px">This message was generated by ${escapeHtml(clinicName)}. Do not reply with sensitive medical information.</td></tr>
      </table>
    </td></tr></table>
  </body></html>`;
}

function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

export async function deliverQueuedEmail(queueItem) {
  const transport = getTransporter();
  const payload = typeof queueItem.payload_json === 'string' ? JSON.parse(queueItem.payload_json || '{}') : queueItem.payload_json || {};
  const info = await transport.sendMail({
    from: env.SMTP_FROM,
    to: queueItem.recipient,
    subject: queueItem.subject,
    html: templateHtml(queueItem.template, { ...payload, subject: queueItem.subject }),
    text: payload.text || `${payload.title || queueItem.subject}\n\n${String(payload.message || '').replace(/<[^>]+>/g, '')}`
  });
  return info;
}
